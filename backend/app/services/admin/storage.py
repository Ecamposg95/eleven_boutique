"""Where processed images live. A future S3 backend only has to implement StorageBackend."""

import os
import re
import tempfile
from pathlib import Path
from typing import Protocol

from app.config import Settings

_SAFE_KEY = re.compile(r"[a-f0-9]{32}\.(jpg|png|webp)")
URL_PREFIX = "/media"


class StorageBackend(Protocol):
    def save(self, key: str, data: bytes, content_type: str) -> None: ...

    def delete(self, key: str) -> None: ...

    def url(self, key: str) -> str: ...


class LocalStorage:
    def __init__(self, root: Path) -> None:
        self.root = root

    def _path(self, key: str) -> Path:
        # Keys are generated by the pipeline; this keeps any other value away from the disk.
        if not _SAFE_KEY.fullmatch(key):
            raise ValueError("Invalid storage key")
        return self.root / key

    def save(self, key: str, data: bytes, content_type: str) -> None:
        path = self._path(key)
        self.root.mkdir(parents=True, exist_ok=True)
        descriptor, temporary = tempfile.mkstemp(dir=self.root, suffix=".tmp")
        try:
            with os.fdopen(descriptor, "wb") as handle:
                handle.write(data)
            os.chmod(temporary, 0o644)
            os.replace(temporary, path)
        except BaseException:
            Path(temporary).unlink(missing_ok=True)
            raise

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def url(self, key: str) -> str:
        self._path(key)
        return f"{URL_PREFIX}/{key}"


def get_storage(settings: Settings) -> StorageBackend:
    return LocalStorage(settings.resolved_media_root)
